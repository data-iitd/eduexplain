"""Stage 5: verified realisation (paper §3, grounded realisation).

Narration u_ℓ: generated by the instruction-tuned LLM from (role, S_ℓ, query) and
accepted only if every check-worthy claim is entailed (p_entail ≥ θ_e) by some
premise from desc(r), r ∈ S_ℓ. Failing drafts are regenerated with the
unsupported claims as feedback, up to `max_regen` generations in total.

On-screen o_ℓ: judged for fidelity to the narration (not for independent
grounding). If S_ℓ has a figure, the directive must show that figure and its
annotation must not be contradicted by the narration. Otherwise the rendered
text/visual must not be contradicted by the narration. "Not contradicted"
means p_contra < θ_c = 0.2: the strict entailment mode over-penalised on-screen
descriptions, which paraphrase visually.
"""
import json
import re
from typing import Callable, Dict, List, Optional, Tuple

from data import ModalType, Resource

DEFAULT_MAX_REGEN = 3


def _sentence_split(text: str) -> List[str]:
    parts = re.split(r"(?<=[.!?])\s+", (text or "").strip())
    return [p for p in parts if p]


# Sentences that are pure spoken framing / back-reference / preview, not
# factual claims about the source. They are neither verified nor counted.
_DISCOURSE_RE = re.compile(
    r"^\s*(?:"
    r"let(?:'s|’s)\b|let us\b|"
    r"here(?:'s|’s)\b|"
    r"(?:now|next|first|finally|so|okay|alright)[,]?\s+"
    r"(?:let(?:'s|’s)|let us|we(?:'ll|’ll| will)|take a look|look at|consider)\b|"
    r"to (?:recap|summari[sz]e|review|wrap up)\b|"
    r"in (?:summary|short|recap|conclusion)\b|"
    r"we(?:'ve|’ve| have)(?: already)? "
    r"(?:seen|discussed|talked|covered|learned|mentioned|looked)\b|"
    r"we(?:'ll|’ll| will) (?:focus|look|explore|see|start|begin|discuss|cover|now)\b|"
    r"as we (?:mentioned|discussed|saw|said|covered)\b"
    r")",
    re.IGNORECASE,
)


def is_checkworthy(sentence: str) -> bool:
    """False for questions and pure framing sentences."""
    t = sentence.strip()
    return bool(t) and not t.endswith("?") and _DISCOURSE_RE.match(t) is None


def build_premises(resources: List[Resource]) -> List[str]:
    """Premises from desc(r): every sentence plus adjacent two-sentence windows
    within a resource (NLI cross-encoders degrade on long premises)."""
    premises, seen = [], set()
    for r in resources:
        ss = _sentence_split(r.content)
        for c in ss + [ss[i] + " " + ss[i + 1] for i in range(len(ss) - 1)]:
            if c not in seen:
                seen.add(c)
                premises.append(c)
    return premises


class NarrationVerifier:
    """NLI verdicts for narration grounding (entailment ≥ θ_e) and on-screen
    fidelity (contradiction < θ_c). `nli` is a backend.BatchedNLI."""

    def __init__(self, nli, entail_threshold: float = 0.5, contra_threshold: float = 0.2):
        self.nli = nli
        self.theta_e = entail_threshold
        self.theta_c = contra_threshold

    def claim_verdicts(self, narration: str, resources: List[Resource]) -> List[Tuple[str, str]]:
        """(sentence, "skip" | "supported" | "unsupported") per sentence.
        The single source of truth for both enforcement and the NG metric."""
        sents = _sentence_split(narration or "")
        premises = build_premises(resources)
        claims = [c for c in sents if is_checkworthy(c)]
        pairs = [(p, c) for c in claims for p in premises]
        best: Dict[str, float] = {}
        if pairs:
            for (p, c), e in zip(pairs, self.nli.entail(pairs)):
                best[c] = max(best.get(c, 0.0), float(e))
        out = []
        for c in sents:
            if not is_checkworthy(c):
                out.append((c, "skip"))
            else:
                out.append((c, "supported" if best.get(c, 0.0) >= self.theta_e else "unsupported"))
        return out

    def verify_narration(self, narration: str, resources: List[Resource]) -> Tuple[bool, List[str]]:
        if not narration or not narration.strip():
            return False, ["<empty or missing narration>"]
        bad = [c for c, v in self.claim_verdicts(narration, resources) if v == "unsupported"]
        return not bad, bad

    def not_contradicted(self, premise: str, hypothesis: str) -> bool:
        return float(self.nli.contra([(premise, hypothesis)])[0]) < self.theta_c


