def build_segment_prompt(query: str, role: str, resources: List[Resource],
                         prior_narrations: Optional[List[str]] = None,
                         feedback: Optional[List[str]] = None) -> str:
    has_figure = any(r.modality == ModalType.IMAGE for r in resources)
    tagged = []
    for r in resources:
        tag = "FIGURE" if r.modality == ModalType.IMAGE else "TEXT"
        tagged.append(f"[{tag}|id={r.rid}] {r.content}")
    grounded_material = "\n".join(tagged)

    info = ROLE_INSTRUCTIONS.get(role, {
        "purpose": "fulfil this segment's pedagogical function using only the grounded material",
        "guidance": "State the grounded facts most relevant to this role and the query, combined into coherent sentences.",
    })

    if has_figure:
        onscreen_rule = (
            "A figure is included above. In \"onscreen\", describe a light annotation layered on "
            "top of it -- an arrow, a highlight box/circle, a short text callout, a zoom/pan, or a "
            "checkmark/X, drawn from what the figure actually shows. The figure itself will be "
            "named automatically -- write the annotation only."
        )
    else:
        onscreen_rule = (
            "No figure is available for this segment. In \"onscreen\", describe a concrete "
            "text-highlight (title card, key-term card, bullet layout, equation card) or a simple "
            "generic visual (basic shapes/arrows, a plain before/after or comparison layout), keeping "
            "the level of visual detail generic rather than precise domain-specific rendering."
        )

    prior_block = ""
    if prior_narrations:
        joined = "\n".join(f"- {n}" for n in prior_narrations[-3:])
        prior_block = (
            f"\nALREADY SAID in earlier segments -- write something new that fulfils THIS role "
            f"instead of repeating these:\n{joined}\n"
        )

    feedback_block = ""
    if feedback:
        joined = "\n".join(f"- {c}" for c in feedback[:6])
        feedback_block = (
            f"\nYOUR PREVIOUS DRAFT contained claims that are NOT supported by the grounded "
            f"material:\n{joined}\n"
            f"Rewrite the segment so that every sentence is directly supported by the grounded "
            f"material. Remove or replace the unsupported content and stay close to the "
            f"material's own wording.\n"
        )

    system = (
        f"You are producing ONE segment of a resource-grounded educational video storyboard.\n"
        f"ROLE: \"{role}\" -- {info['purpose']}.\n"
        f"{info['guidance']}\n\n"
        f"Base everything on the grounded material below and the query -- draw only on facts that "
        f"are actually there, and select only the parts of the material relevant to this role and "
        f"this query (you do not need to use all of it). You may combine, paraphrase, and "
        f"synthesize across several of the material's sentences in your own words; you are not "
        f"limited to lifting one sentence verbatim. \"narration\" should be one coherent piece of "
        f"speech with enough substance to actually fulfil the role above -- audio only, so do not "
        f"describe anything visual in it.\n\n"
        f"{onscreen_rule}\n"
        f"Keep \"onscreen\" to 1-3 sentences; put literal on-screen text in quotes; give rough "
        f"position (top/center/bottom, left/right).\n"
        f"{prior_block}{feedback_block}\n"
        'Respond with ONLY {"narration": "...", "onscreen": "..."} -- no preamble, no fences.'
    )
    return (
        f"{system}\n\n"
        f"QUERY: \"{query}\"\n"
        f"GROUNDED MATERIAL:\n---\n{grounded_material}\n---\n\n"
        f"JSON:"
    )


def _unescape(s: str) -> str:
    return (s.replace('\\"', '"').replace("\\n", "\n")
             .replace("\\t", "\t").replace("\\\\", "\\"))


def parse_segment(raw: str) -> Tuple[str, str]:
    cleaned = re.sub(r"^```(json)?|```$", "", (raw or "").strip(), flags=re.MULTILINE).strip()
    m = re.search(r"\{.*\}", cleaned, re.DOTALL)
    for cand in ([m.group(0)] if m else []) + [cleaned]:
        try:
            obj = json.loads(cand)
            return str(obj.get("narration", "")).strip(), str(obj.get("onscreen", "")).strip()
        except (json.JSONDecodeError, AttributeError, TypeError):
            pass
    # truncated / slightly malformed JSON: salvage the fields
    m = re.search(r'"narration"\s*:\s*"((?:[^"\\]|\\.)*)"\s*,\s*"onscreen"\s*:\s*"((?:[^"\\]|\\.)*)"?',
                  cleaned, re.DOTALL)
    if m:
        return _unescape(m.group(1)).strip(), _unescape(m.group(2)).strip()
    return "", ""


def make_segment_generator(llm, max_new_tokens: int = 400) -> Callable[..., Tuple[str, str]]:
    """llm: callable(prompt, max_new_tokens) -> text (backend.HFChatLLM)."""
    def _generate(query, role, resources, prior_narrations=None, feedback=None):
        prompt = build_segment_prompt(query, role, resources, prior_narrations, feedback)
        return parse_segment(llm(prompt, max_new_tokens))
    return _generate


def generate_grounded_segment(query: str, role: str, resources: List[Resource],
                              verifier: NarrationVerifier, generator: Callable,
                              max_regen: int = DEFAULT_MAX_REGEN,
                              prior_narrations: Optional[List[str]] = None,
                              trace: Optional[Dict] = None) -> Tuple[str, str]:
    """Generate-then-verify. `max_regen` is the total generation budget
    (first draft + max_regen-1 regenerations). If every draft fails, the
    unsupported sentences of the last draft are dropped ("salvage"); if no
    supported sentence remains, a source sentence is used ("extractive")."""
    trace = trace if trace is not None else {}
    attempts = trace.setdefault("attempts", [])
    feedback = None
    narration = onscreen = ""
    for attempt in range(max_regen):
        narration, onscreen = generator(query, role, resources, prior_narrations, feedback=feedback)
        ok, bad = verifier.verify_narration(narration, resources)
        attempts.append({"narration": narration, "onscreen": onscreen, "ok": ok, "unsupported": bad})
        if ok:
            trace["outcome"] = "first" if attempt == 0 else "regen"
            return narration, onscreen
        feedback = [c for c in bad if not c.startswith("<")]
    verdicts = verifier.claim_verdicts(narration, resources)
    kept = [c for c, v in verdicts if v != "unsupported"]
    if kept and any(v == "supported" for _, v in verdicts):
        trace["outcome"] = "salvage"
        return " ".join(kept), onscreen
    cands = [s for r in resources for s in _sentence_split(r.content)]
    used = {s for n in (prior_narrations or []) for s in _sentence_split(n)}
    pick = next((c for c in cands if c not in used), cands[0] if cands else narration)
    trace["outcome"] = "extractive"
    return pick, f"On-screen text: {pick[:160]}"


_FIGURE_CLAIM_RE = re.compile(r"\bfigure\s+\S+\s+(?:is\s+shown|shown)\b\.?\s*", re.IGNORECASE)


def route_onscreen(narration: str, llm_onscreen: str, resources: List[Resource]) -> Tuple[str, str]:
    """If S_ℓ has a figure it is always shown, with the LLM's annotation on top."""
    fig = next((r for r in resources if r.modality == ModalType.IMAGE), None)
    cleaned = _FIGURE_CLAIM_RE.sub("", llm_onscreen or "").strip()
    if fig is not None:
        return f"Figure {fig.rid} is shown. {cleaned}".strip(), "figure"
    return (cleaned or f"On-screen text: {(narration or '')[:160]}"), "text_render"


def verify_fidelity(narration: str, onscreen: str, resources: List[Resource],
                    verifier: NarrationVerifier) -> bool:
    """Fid rule (paper §4.3). It depends only on (u_ℓ, o_ℓ, S_ℓ), not on which
    method produced the segment:
      figure in S_ℓ  -> the directive shows that figure, and its annotation is
                        not contradicted by the narration;
      otherwise      -> the directive is non-empty and not contradicted by the
                        narration."""
    narration, onscreen = (narration or "").strip(), (onscreen or "").strip()
    if not narration or not onscreen:
        return False
    fig = next((r for r in resources if r.modality == ModalType.IMAGE), None)
    if fig is not None:
        if fig.rid not in onscreen:
            return False
        annotation = re.sub(rf"^Figure\s+{re.escape(fig.rid)}\s+is\s+shown\.?\s*", "", onscreen).strip()
        return (not annotation) or verifier.not_contradicted(narration, annotation)
    return verifier.not_contradicted(narration, onscreen)


def realize_segment(query: str, role: str, resources: List[Resource], verifier: NarrationVerifier,
                    segment_generator: Callable, max_regen: int = DEFAULT_MAX_REGEN,
                    prior_narrations: Optional[List[str]] = None,
                    trace: Optional[Dict] = None) -> Tuple[str, str, str]:
    """Realise one segment. `trace` records what is needed to derive the
    "w/o NLI" and "− on-screen fidelity" variants without new generation:
    every attempt (attempts[0] is the unverified first draft), and the routed
    directive before the fidelity fallback."""
    trace = trace if trace is not None else {}
    narration, llm_onscreen = generate_grounded_segment(
        query, role, resources, verifier, segment_generator, max_regen, prior_narrations, trace)
    onscreen, src = route_onscreen(narration, llm_onscreen, resources)
    trace["onscreen_raw"], trace["src_raw"] = onscreen, src
    trace["fid_pass"] = verify_fidelity(narration, onscreen, resources, verifier)
    if not trace["fid_pass"]:
        onscreen, src = f"On-screen text: {narration[:160]}", "text_render"

    # "w/o NLI verification": the unverified first draft, same on-screen rule
    first = trace["attempts"][0]
    nv_on, nv_src = route_onscreen(first["narration"], first["onscreen"], resources)
    if not verify_fidelity(first["narration"], nv_on, resources, verifier):
        nv_on, nv_src = f"On-screen text: {first['narration'][:160]}", "text_render"
    trace["noverify"] = {"narration": first["narration"], "onscreen": nv_on, "src": nv_src}
    return narration, onscreen, src
